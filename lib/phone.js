// Український номер для заявок. Ті самі правила, що в формі (site/main.js).
// Приймає «093 291 88 77», «+380932918877», «380932918877», «0932918877»
// (і стару маску «+38 (093) 291-88-77»). Номер: 10 цифр, починається з 0 і коду
// оператора чи міста: 03x–06x (міські, 050/063/066/067/068), 073, 09x. Повертає «093 291 88 77».

export const TASK_MIN = 4; // мінімум символів у «Що зробити»

export function normalizePhone(value) {
  let d = String(value || "").replace(/\D/g, "");
  if (d.length === 12 && d.startsWith("380")) d = d.slice(2);
  if (!/^0(?:[3-6]\d|73|9\d)\d{7}$/.test(d)) return null;
  return `${d.slice(0, 3)} ${d.slice(3, 6)} ${d.slice(6, 8)} ${d.slice(8)}`;
}
